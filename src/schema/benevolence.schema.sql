DROP TABLE CUSTOMER_PROFILE;

CREATE TABLE IF NOT EXISTS CUSTOMER_PROFILE (
CSTMR_PRFL_ID INT AUTO_INCREMENT PRIMARY KEY COMMENT 'Table auto generated primary key',
EMAIL VARCHAR(30) UNIQUE COMMENT 'Users email address',
ATHNT_CSTMR_PRFL_ID VARCHAR(30) COMMENT 'Authorize.net customer profile id',
CRTD_DT TIMESTAMP COMMENT 'Created date - auto generated timestamp' DEFAULT CURRENT_TIMESTAMP,
UPDTD_DT TIMESTAMP COMMENT 'Last updated date - auto generated timestamp' DEFAULT CURRENT_TIMESTAMP
);

DROP TABLE CUSTOMER_CONTRIBUTIONS;

CREATE TABLE IF NOT EXISTS
CUSTOMER_CONTRIBUTIONS (
CNTRBTN_ID INT AUTO_INCREMENT PRIMARY KEY COMMENT 'Table auto generated primary key',
AMNT DECIMAL(15,2) COMMENT 'Amount contributed' NOT NULL,
CSTMR_PRFL_ID INT NOT NULL,
TRNSCTN_ID VARCHAR(30) COMMENT 'Authorize.net transaction id',
OCCURENCE VARCHAR(100) COMMENT 'Occurrence of the contribution',
TX_DESC_ID int(11) DEFAULT NULL,
CRTD_DT TIMESTAMP COMMENT 'Created date - auto generated timestamp' DEFAULT CURRENT_TIMESTAMP,
UPDTD_DT TIMESTAMP COMMENT 'Last updated date - auto generated timestamp' DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT CNTRBTNS_PRFL FOREIGN KEY (CSTMR_PRFL_ID)
REFERENCES CUSTOMER_PROFILE (CSTMR_PRFL_ID),
CONSTRAINT TRANSACTION_TYPE_FK FOREIGN KEY(TX_DESC_ID)
REFERENCES                TX_DESC(DESC_ID)
);

CREATE TABLE IF NOT EXISTS TX_DESC(
    DESC_ID INT AUTO_INCREMENT PRIMARY KEY COMMENT 'Table auto generated primary key',
    TX_DESCRIPTION VARCHAR(100) NOT NULL COMMENT 'Transaction description'
);

