module.exports = `SELECT 
CONT.AMNT amount, 
CONT.TRNSCTN_ID transactionId, 
CONT.CRTD_DT createdDate,
CONT.OCCURRENCE occurrence,       
PROF.EMAIL email, 
PROF.ATHNT_CSTMR_PRFL_ID customerProfileId,
META.TX_DESCRIPTION txDescription       
FROM 
CUSTOMER_CONTRIBUTIONS CONT INNER JOIN CUSTOMER_PROFILE PROF
ON CONT.CSTMR_PRFL_ID = PROF.CSTMR_PRFL_ID
INNER JOIN TX_DESC META 
ON META.DESC_ID = CONT.TX_DESC_ID
WHERE UPPER(PROF.EMAIL) = ? 
ORDER BY CONT.CRTD_DT DESC`;
